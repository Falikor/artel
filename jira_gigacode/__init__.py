"""Демон JIRA → GigaCode, разложенный по модулям.

Порядок работы и где что лежит:

    cli            флаги, проверка окружения, основной цикл опроса
     ├─ checks     --check: репозиторий, GigaCode, Jira, Jenkins
     ├─ dry_run    --dry-run: что сделал бы, без изменений
     └─ pipeline   одна задача целиком: генерация → Git → Jenkins → Jira → отчёт
          ├─ gigacode       запуск CLI суб-агента и оценка результата
          │    └─ git_workspace   базовая ветка, рабочая ветка, восстановление прошлой попытки
          ├─ review         независимое ревью и доработка по замечаниям
          ├─ experience     опыт по репозиторию между задачами (memory/{КЭ}.md)
          ├─ git_delivery   временные файлы, коммиты агента, пуш в remote
          ├─ requirements_rework ручные переделки постановки: очередь и отдельный учёт
          ├─ routing        какой сервис (бек/фронт) под КЭ — по названию и лейблам задачи
          ├─ dependencies   допуск связанных задач: backend → frontend, КЭ и разрешающий лейбл
          │    └─ jira_development  ветки Development из Jira и подтверждение изменений через Git
          ├─ jenkins        деплой по лейблам jenkins_*
          ├─ jira_client    REST: поиск, поля, комментарии, переходы
          ├─ reports        комментарии-отчёты в задаче
          ├─ retry          кулдаун и «осталось только перевести»
          └─ tokens         расход токенов GigaCode
     ├─ explore    в простое: исследование задач из бэклога (OpenSpec explore) → комментарий
     ├─ retro      ночью раз в неделю: что стало со сданными задачами → уроки в опыт и outcomes.json
     └─ log_archive  раз в час: большие логи и старые логи GigaCode → logs/archive/ГГГГ-ММ/*.gz

    supervisor     artel.py: запуск, перезапуск и статус всех демонов
    worktree       временные копии репозитория для ревью и исследования

    Общее: base (корень проекта, логгер), config (настройки), logs (лог инстанса,
    причины ошибок, маскировка секретов), runtime (флаги процесса и отчёт для дашборда),
    issue_report (факты текущей задачи для отчёта).

Изменяемые значения процесса (runtime.DRY_RUN, runtime.state, runtime.running)
читаются через модуль runtime, а запросы к Jira — через jira_client.jira_request:
так их можно подменить в тестах в одном месте.
"""

