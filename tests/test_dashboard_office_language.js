'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
function run(language='en') {
  const context={document:{documentElement:{},addEventListener(){}},localStorage:{getItem:()=>language},location:{search:''},URLSearchParams};
  vm.createContext(context);
  for(const file of ['core/i18n.js','office/scene-map.js','office/city-model.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../office_dashboard/static/js',file),'utf8'),context);
  return {context,eval:code=>vm.runInContext(code,context)};
}
test('office status labels and social dialogue initialize in the selected language',()=>{
  const en=run(),ru=run('ru');
  const labels=code=>en.eval(`JSON.stringify(${code})`);
  assert.doesNotMatch(labels('Object.values(STAGE).map(stage=>stage.label)'),/[А-Яа-яЁё]/);
  assert.doesNotMatch(labels('[SOLO,DIALOGS,VISIT_DIALOGS,LINES]'),/[А-Яа-яЁё]/);
  assert.equal(en.eval('STAGE.generating.label'),'GigaCode is coding');
  assert.equal(ru.eval('STAGE.generating.label'),'GigaCode пишет код');
  assert.equal(en.eval('projectKey({ci_id:"42"})'),'CI 42');
  assert.equal(ru.eval('projectKey({ci_id:"42"})'),'КЭ 42');
  assert.equal(en.eval('displayName({ci_id:"42",name:"Имя пользователя <QA>"})'),'Имя пользователя <QA>');
});
test('only explicitly generated building names translate; custom and legacy values stay exact',()=>{
  const {context:c}=run();
  const autogenerated={id:'a',building_level:17,building_title:'Корпус 2',building_title_custom:false,title:'Название офиса'};
  const custom={...autogenerated,id:'b',building_title_custom:true};
  const legacy={...autogenerated,id:'c'};delete legacy.building_title_custom;
  const before=JSON.stringify([autogenerated,custom,legacy]);
  assert.equal(c.cityRoomBuildingTitle(autogenerated),'Building 2');
  assert.equal(c.cityAddressLabel(autogenerated),'Building 2 · floor 1');
  assert.equal(c.cityRoomBuildingTitle(custom),'Корпус 2');
  assert.equal(c.cityRoomBuildingTitle(legacy),'Корпус 2');
  assert.equal(c.cityRoomBuildingTitle({building_level:33}),'Building 3');
  assert.equal(JSON.stringify([autogenerated,custom,legacy]),before);
});
test('district layout and landmarks retain stable addresses while labels are English',()=>{
  const {context:c}=run();
  const rooms=Array.from({length:17},(_,index)=>({id:'office-'+index,building_level:index+1,title:'Офис',building_title_custom:false}));
  const buildings=c.cityLayout(rooms);
  assert.equal(buildings.length,2);assert.deepEqual(Array.from(buildings,b=>b.title),['Building 1','Building 2']);
  assert.equal(buildings[1].rooms[0].floor,1);
  const labels=c.citySurroundings(buildings).map(lot=>lot.title).filter(Boolean);
  assert.doesNotMatch(labels.join(' '),/[А-Яа-яЁё]/);
  assert.ok(labels.includes('SCHOOL'));assert.ok(labels.includes('SHOP'));assert.ok(labels.includes('BAKERY'));
  assert.ok(rooms.every(room=>room.title==='Офис'));
});
